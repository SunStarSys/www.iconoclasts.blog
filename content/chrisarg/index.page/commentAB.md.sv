Om du besöker <https://iconoclasts.blog/>, ska din webbläsare nu be dig aktivera aviseringar.

Vad det gör är att aktivera meddelanden på din bärbara dator som berättar när någon annan gör ändringar på sidor som du prenumererar på (aka tittar).

Du kan visa din lista över tillgängliga meddelanden genom att skriva "meddela=" i sökfältet längst upp till höger i navigeringsfältet.

