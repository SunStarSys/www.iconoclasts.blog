Tänk på att det mesta av det befintliga användarforumet distribuerar mod_apreq2 i ett kluster på mellannivå bakom HTTPS-nätslussar, så den statistik som rapporteras av <https://webtechsurvey.com/technology/mod_apreq2> representerar endast en bråkdel av den totala distribuerade användarbasen.

