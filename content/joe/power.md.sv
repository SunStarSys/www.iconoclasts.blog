### Fallout

Det är inte voodoo att få en epidemi att börja röra sig bort från [exponentiell tillväxt]

Vad epidemiologer försöker åstadkomma är att sparka igång den processen så snart som möjligt.  Varje förlorad dag innebär en accelererande förlust av liv, ökad momentum av allvarliga fall och större risk för att helt överväldiga hälso- och sjukvården som grafen spricker.

Oundvikligen kommer utplattningen att ske. Om det inte är på grund av mänsklig social visdom, beror det på att viruset inte kan infektera tidigare offer <sup>2</sup>, och det infekterar helt enkelt majoriteten av befolkningen innan det peterar ut och dröjer sig för att infektera nyfödda eller bara försvinner helt.

