### Matematik

Till en början är exponentiella funktioners värden mikroskopiskt små och ökar knappt över tiden (på `x-axel`

![COVID-19 i mars 2020]

För att illustrera detta analogt: föreställ dig hur snabbt du skulle gå nu om din bils hastighet alltid var bunden, genom en proportionalitetskonstant, till körsträckan på vägmätaren. Under denna hypotetiska, för varje fast tidsintervall som passerar, både bilens hastighet och totala avstånd reste *multiplies * med samma fasta belopp (större än en). I själva verket är det [sköldpaddor hela vägen ner](https://en.wikipedia.org/wiki/Turtles_all_the_way_down): din bils acceleration, ryck, etc. (dvs alla [derivat]

På en [logaritmisk skala](https://en.wikipedia.org/wiki/Logarithmic_scale) för `y-axel`, grafer av sådana effektfunktioner visas som ** raka linjer**.  De två diagrammen nedan har parallella tillväxtlinjer (som jag lade till i svart till dessa [världsometrar](https://www.worldometers.info/coronavirus/) källor) och reflekterar samma *världsomfattande* totaler som paret ovan. Om vi representerar dessa "linjer" i `log y = mx + b` formen, `mn`-värden (`sluttningar`) instämmer; endast `b)`-värden (`logga y-avlyssningar`) olika.  Den viktigaste punkten här är att fokusera uppmärksamheten på ** invariant** `sluttning`inte den varierande `fånga`, för alla typer av pandemistatistik per ålder eller per geografisk region, eller kombinationer av dessa.  Multiplicera `ln 10 = 2.302585...` med `sluttning` Detta ger den grundläggande proportionalitetskonstanten som likställer de avbildade exponentiella funktionernas värden med deras * ögonblickliga* förändringstakt.  Med andra ord fokusera på de relativa procentandelarna mellan olika statistik, som [villkorlig](https://en.wikipedia.org/wiki/Conditional_expectation) dödstal, är *saknar poängen*: det är en konversation om `b)`-värden, inte `mn`

För att vara tydlig, skillnaden i `b)`-värden handlar mer om tidsskillnader på `x-axel` än det är skillnader i `y`-värden; i form av ekvationer: `log y = mx + b = m(x + b/m)` är en implicit översättning av raden `y = mx`, `b)` enheter längs `y-axel`eller likvärdigt `per minut` enheter längs `x-axel` (i motsatt riktning). **Valfri** typ av relativ statistik (t.ex. dödlighetsgrad för fall) kan fångas när det gäller sådana tidsöversättningar, en gång `mn` är känd (och icke-noll).  Den *kritiska* statistiken är `mn`

