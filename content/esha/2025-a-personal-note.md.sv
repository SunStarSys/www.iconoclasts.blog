Nästa dag bestämde sig mannen som varit min partner de senaste två åren för att f*ck någon annan istället för att stanna och trösta mig. När jag snabbt försökte komma till min farbrors begravning försvann han. Jag gick ombord på flygplanet. När jag landade var jag inne för en stor överraskning. Så fort jag tog min telefon ur flygplansläge blev jag träffad med en pornografisk video från den andra kvinnan. Jag var på en flygplats, och jag visste inte hur jag skulle bearbeta det. Så jag gjorde vad jag naturligtvis gjorde när jag hade ett problem som jag inte kunde lösa och försökte ringa min älskade farbror Shekhar. Men den här gången bara för att inse att han var borta.

Mannen jag trodde att jag älskade, och som jag felaktigt trodde älskade mig, visade mig mindre medkänsla än slumpmässiga främlingar. En flygvärdinna på Finnair såg mitt sorgande ansikte och flyttade mig upp till business class så att jag kunde gråta privat. För att lägga till förolämpning mot skada, den andra kvinnan, som om att dansa på min farbrors grav, skickade mig extremt äckliga meddelanden ([Klicka här för att läsa, jag vill inte återuppleva detta](https://x.com/eshaLegal/status/1954670433904492945?s=20)).

Detta dubbla trauma och svek slog mig hårt. Jag kunde inte sörja för min farbror eftersom varje gång jag försökte, skulle det andra förräderiet invadera mina minnen. Jag kunde inte skriva, forska eller göra andra uppgifter som gjorde Historic.ly möjligt.

Efter ett tag kunde jag få min PTSD behandlad och psykologiskt förbättra tillräckligt för att vara funktionell. Jag bestämde mig för att omtolka traumat som en sista gåva från min farbror från himlen och visa mig den sanna naturen hos mannen som var uppenbart ovärdig. Jag har så många bra minnen av min farbror, som den tid han tog mig till Disneyland.

För de av er som stannade som betalda abonnenter under denna tid finns det inga ord att tacka er.

För er som valt att avregistrera er vill jag be om ursäkt. Jag är verkligen ledsen. Jag sviker dig. För det har jag inga ursäkter, och jag försöker bygga upp ditt förtroende. Jag hoppas att du kommer att tänka om och bli prenumerant igen.

Jag hoppas att under den senaste veckan eller två har jag kompenserat för bristen på innehåll. Jag avser att fortsätta 2026, starkt med min serie om varje antikommunistisk pratpunkt debunked:

