Jag skriver sällan personliga inlägg eftersom jag tycker att de är svåra och irrelevanta för arbetet. Men {# lede #}Jag måste förklara min långa frånvaro i år och tacka alla som fortsatte att stödja detta projekt.{# lede #}.

Det här året har varit väldigt svårt, och det här är det svåraste blogginlägget jag någonsin skrivit.

Den 13 juni dog min älskade farbror Shekhar. Han var inte bara min farbror - folk brukade skämta om hur nära vi var. Folk skulle skämta om att jag var hans äldsta dotter. Jag var förkrossad. Men om det var min farbrors död ensam, skulle jag inte ha varit dysfunktionell.

