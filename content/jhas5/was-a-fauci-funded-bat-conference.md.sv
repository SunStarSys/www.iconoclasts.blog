## Fladdermöss är sociala däggdjur, precis som vi människor

Linfa och Dani lämnade Wuhan i slutet av november för en konferens i Singapore i början av december 2019. De mötte upp Shi på deras Duke Singapore campus, med sitt BSL3 bat lab, och alla hoppade i en hytt för den snabba 10-minuters resa till konferenscentret.

I december 2019 spred sig ett smittsamt fladdermusvaccin, som snart skulle döpas om till SARS2, redan utanför Wuhan. Eftersom det inte fanns något PCR-test, och de visste inte ens vad det var, fortsatte Dani, Linfa och Shi sitt yrkesliv. Detta var en stor internationell bat konferens för en "liten grupp" av specialiserade bat virologer.

Dani hävdade "det fanns inget prat" men Singapore var förmodligen grund noll för spridningen av Wuhan lunginflammation. När det namnlösa viruset spred sig, "okänt för de forskare som deltog", började några sprida rykten.

Ett 2019 NIH-finansierat överförbart vaccinforskningspapper spekulerade om utbredda händelser som denna. De "individer som är mest benägna att sprida en sjukdom (dvs. superspridare)" inom den lilla, snäva internationella virologi gemenskapen är Shi, Linfa och Dani. De är "högt anslutna noder" och skulle socialisera, som däggdjursfladdermöss, och starta "processen att vaccinera "bekanta" av slumpmässigt utvalda individer."

## Funktionsvinstpartiet 2019

De virologer som deltog i denna december 2019 Singapore konferens var glada. De har varit tillbaka i Gain-of-Function-verksamheten i två år, så det är dags att diskutera sina senaste djurvaccinprodukter.

Gain-of-Function (GoF) forskning slutade aldrig, som en anonym långvarig NIH-tjänsteman sa: "Om du förbjuder GoF forskning, förbjuder du all virologi." "Ända sedan moratoriet (2014) har alla gått blinka och bara gjort GoF forskning ändå." Fauci sa i början av 2019 att det var ett bra beslut att låta forskningen officiellt återupptas.

Fauci's NIH lyfte pausen på GoF veckan före jul 2017, då alla lämnade Washington DC. Den 50-åriga byråkraten visste hur man skulle utnyttja en presidentadministrationsförändring. Detta var en ledarfri tidsperiod när HHS-sekreteraren (chef för NIH, FDA, CDC) avgick i september 2017, men innan hans ersättare bekräftades och svor i januari 2018. Fauci diskuterade även de musikaliska stolarna i HHS (2:00). Detta skedde under en tvåårsperiod utan en Vita husets OSTP-direktör.

